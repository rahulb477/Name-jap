function dayOfYear(d = new Date()): number {
  const start = Date.UTC(d.getFullYear(), 0, 0);
  const now = Date.UTC(d.getFullYear(), d.getMonth(), d.getDate());
  return Math.round((now - start) / 86_400_000);
}

export function thoughtForToday(d = new Date()): GitaVerse {
  const idx = (dayOfYear(d) - 1) % GITA_VERSES.length;
  return GITA_VERSES[idx < 0 ? 0 : idx];
}

export function quoteInLang(verse: GitaVerse, lang: ThoughtLang): string {
  return verse.quote[lang] ?? verse.quote.en;
}
