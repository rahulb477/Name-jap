export const LANGUAGES = [
  { code: "en", native: "English", english: "English (System Default)", dict: en },
  { code: "as", native: "অসমীয়া", english: "Assamese", dict: as },
  { code: "doi", native: "डोगरी", english: "Dogri", dict: doi },
  { code: "gu", native: "ગુજરાતી", english: "Gujarati", dict: gu },
  { code: "hi", native: "हिन्दी", english: "Hindi", dict: hi },
] as const;

export type LangCode = (typeof LANGUAGES)[number]["code"];

type I18nCtx = {
  lang: LangCode;
  isSet: boolean;
  setLang: (l: LangCode) => void;
  t: (k: DictKey) => string;
};

const Ctx = createContext<I18nCtx | null>(null);

function loadLang(): LangCode | null {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return LANGUAGES.some((l) => l.code === v) ? (v as LangCode) : null;
  } catch {
    return null;
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode | null>(loadLang);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (k: DictKey) => {
      const found = LANGUAGES.find((l) => l.code === lang);
      return found ? found.dict[k] : en[k];
    },
    [lang],
  );

  const value = useMemo<I18nCtx>(
    () => ({ lang: lang ?? "en", isSet: lang !== null, setLang, t }),
    [lang, setLang, t],
  );

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
